import { cpSync, existsSync, rmSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const source = resolve('dist')
const destination = resolve('docs')
const marker = resolve(destination, '.digikaren-generated')
if (!existsSync(resolve(source, 'index.html'))) throw new Error('Run the Pages build before preparing docs/.')
if (existsSync(destination) && !existsSync(marker)) throw new Error('docs/ already exists and is not marked as generated; refusing to overwrite it.')
rmSync(destination, { recursive: true, force: true })
cpSync(source, destination, { recursive: true })
writeFileSync(marker, 'Generated by npm run pages:prepare. Do not edit by hand.\n')
console.log('GitHub Pages files prepared in docs/.')
